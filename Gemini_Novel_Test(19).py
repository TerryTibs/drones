# 1. CANONICAL LAMB-OSEEN TIP-VORTEX WAKE FILAMENT MODEL
# =============================================================================
class BurnhamHallockWakeField:
    """
    Computes 3D induced velocity field generated by the lead drone's trailing
    counter-rotating tip vortices. Features an induced downwash core between
    rotors and an energetic upwash harvesting flank outside the vortex lines.
    """

    def __init__(self, span=SPAN_EFF, r_core=VORTEX_CORE_RADIUS, rho=AIR_DENSITY):
        self.b = span
        self.r_c = r_core
        self.rho = rho

    def compute_induced_velocity(self, eval_pos, leader_pos, leader_vel, leader_thrust):
        N = eval_pos.shape[0]
        fwd_speed = safe_norm(leader_vel[:, 0:2], dim=-1, keepdim=True).clamp(min=1.5)

        # Circulation magnitude Gamma_0 = Thrust / (rho * v_forward * b)
        gamma_0 = leader_thrust / (self.rho * fwd_speed * self.b).clamp(min=1e-3)
        gamma_0 = torch.clamp(gamma_0, min=1.0, max=24.0)

        delta = eval_pos - leader_pos
        dx = delta[:, 0:1]
        dy = delta[:, 1:2]
        dz = delta[:, 2:3]

        wake_decay = torch.exp(torch.clamp(dx / 6.0, max=0.0))

        # Vortex lines shed at y = +b/2 (Left tip) and y = -b/2 (Right tip)
        y_v = self.b * 0.5
        r_left_sq = (dy - y_v) ** 2 + dz**2 + self.r_c**2
        r_right_sq = (dy + y_v) ** 2 + dz**2 + self.r_c**2

        # Rigorous Biot-Savart vortex pair:
        # Air pushed DOWN between tips (|dy| < y_v), curls UP outside (|dy| > y_v)
        wz_left = (gamma_0 / (2.0 * math.pi)) * ((dy - y_v) / r_left_sq)
        wz_right = -(gamma_0 / (2.0 * math.pi)) * ((dy + y_v) / r_right_sq)
        w_z = (wz_left + wz_right) * wake_decay

        wy_left = -(gamma_0 / (2.0 * math.pi)) * (dz / r_left_sq)
        wy_right = (gamma_0 / (2.0 * math.pi)) * (dz / r_right_sq)
        w_y = (wy_left + wy_right) * wake_decay
        w_x = -0.12 * torch.abs(w_z)

        v_induced = torch.cat([w_x, w_y, w_z], dim=-1)
        return torch.where(dx > 0.1, torch.zeros_like(v_induced), v_induced)



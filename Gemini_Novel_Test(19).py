# 3. ROBUST CYCLIC PROJECTION QP SAFETY & CONTRACTION FILTER
# =============================================================================
class RobustQPSafetyFilter:
    """
    Exact, unconditionally stable cyclic Dykstra projection filter.
    Solves: min_u 0.5 * ||u - u_nom||^2  s.t.  A u <= b,  u_min <= u <= u_max.
    Strictly 2D vectorization ([N, 3] and [N, 1]): zero memory leaks or tensor expansion.
    """

    def __init__(self, iters=8):
        self.iters = iters

    def solve(self, u_nom, A, b, u_min, u_max):
        u = torch.clamp(u_nom, u_min, u_max).clone()
        k = A.shape[1]

        for _ in range(self.iters):
            for i in range(k):
                a_i = A[:, i, :]  # [N, 3]
                b_i = b[:, i, 0:1]  # [N, 1]

                # a_i^T * u - b_i
                viol = torch.sum(a_i * u, dim=-1, keepdim=True) - b_i  # [N, 1]
                viol_val = F.relu(viol)  # [N, 1]

                a_norm_sq = torch.sum(a_i * a_i, dim=-1, keepdim=True).clamp(min=1e-6)  # [N, 1]
                step = (viol_val / a_norm_sq) * a_i  # [N, 1] * [N, 3] -> [N, 3]
                u = torch.clamp(u - step, u_min, u_max)  # [N, 3]

        return u



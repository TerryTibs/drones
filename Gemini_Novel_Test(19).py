class CertifiedWakeSurfingEnv:
    """
    Two-Quadrotor Aerodynamic Formation Environment with Lamb-Oseen wake coupling.
    Lead drone generates wake; follower identifies upwash zone and rides it
    under NCM contraction guarantees and CBF barrier enforcement.
    """

    def __init__(self, num_envs=1, dt=0.015, device=DEVICE):
        self.num_envs = num_envs
        self.dt = dt
        self.device = device

        self.wake_model = BurnhamHallockWakeField()
        self.qp_filter = RobustQPSafetyFilter(iters=8)

        d = ARM_LENGTH / math.sqrt(2.0)
        c_q = TORQUE_TO_THRUST_RATIO
        B = torch.tensor(
            [
                [1.0, 1.0, 1.0, 1.0],
                [d, -d, d, -d],
                [-d, d, d, -d],
                [-c_q, -c_q, c_q, c_q],
            ],
            device=device,
            dtype=torch.float32,
        )
        self.B_inv = torch.pinverse(B)
        self.sim_time = 0.0

        self.reset()

    def reset(self):
        N = self.num_envs
        self.sim_time = 0.0

        self.lead_pos = torch.zeros((N, 3), device=self.device)
        self.lead_pos[:, 2] = 6.0
        self.lead_vel = torch.zeros((N, 3), device=self.device)
        self.lead_vel[:, 0] = 3.5

        # Optimal upwash sweet spot offset: Trailing by 1.8m, on right flank by (y_v + 0.22m)
        self.sweet_spot_offset = torch.tensor(
            [-1.8, -(SPAN_EFF * 0.5 + 0.22), 0.0], device=self.device
        )

        self.follow_pos = self.lead_pos + self.sweet_spot_offset
        self.follow_vel = self.lead_vel.clone()

        self.lead_rot = torch.eye(3, device=self.device).unsqueeze(0).repeat(N, 1, 1)
        self.follow_rot = self.lead_rot.clone()

        self.lead_thrust = torch.full((N, 1), DRONE_MASS * GRAVITY, device=self.device)
        self.follow_thrust = self.lead_thrust.clone()
        self.follow_motors = torch.full((N, 4), (DRONE_MASS * GRAVITY) / 4.0, device=self.device)

        self.metrics = {}

    def step(self, ncm_net):
        N = self.num_envs
        self.sim_time += self.dt

        # 1. Lead drone flies a smooth periodic formation circuit
        omega_lead = 0.18
        radius_lead = 14.0
        lead_x = radius_lead * math.sin(omega_lead * self.sim_time)
        lead_y = radius_lead * 0.5 * math.sin(2.0 * omega_lead * self.sim_time)
        lead_vx = radius_lead * omega_lead * math.cos(omega_lead * self.sim_time)
        lead_vy = radius_lead * omega_lead * math.cos(2.0 * omega_lead * self.sim_time)

        self.lead_pos[:, 0] = lead_x
        self.lead_pos[:, 1] = lead_y
        self.lead_pos[:, 2] = 6.0
        self.lead_vel[:, 0] = lead_vx
        self.lead_vel[:, 1] = lead_vy
        self.lead_vel[:, 2] = 0.0

        lead_speed = safe_norm(self.lead_vel[:, :2], dim=-1, keepdim=True).clamp(min=1e-3)
        lead_heading = self.lead_vel[:, :2] / lead_speed
        self.lead_rot[:, 0, 0] = lead_heading[:, 0]
        self.lead_rot[:, 1, 0] = lead_heading[:, 1]
        self.lead_rot[:, 0, 1] = -lead_heading[:, 1]
        self.lead_rot[:, 1, 1] = lead_heading[:, 0]

        self.lead_thrust = torch.full((N, 1), DRONE_MASS * GRAVITY + 0.35, device=self.device)

        # 2. Dynamic wake calculation at follower's actual physical position
        v_induced = self.wake_model.compute_induced_velocity(
            self.follow_pos, self.lead_pos, self.lead_vel, self.lead_thrust
        )
        wz_experienced = v_induced[:, 2:3]

        # 3. Layer 1 Macro-Planner Target: Lead-relative sweet spot oriented along leader's heading
        target_pos = self.lead_pos + torch.matmul(self.lead_rot, self.sweet_spot_offset.unsqueeze(-1)).squeeze(-1)
        target_vel = self.lead_vel

        # 4. Closed-loop Nominal Tracking Control
        error_pos = self.follow_pos - target_pos
        error_vel = self.follow_vel - target_vel
        u_nom = -3.5 * error_pos - 2.8 * error_vel

        # 5. Layer 2 Certified Safety Layer (NCM Contraction + CBF QP)
        state_error = torch.cat([error_pos, error_vel], dim=-1)
        M = ncm_net(state_error)
        P_sub = M[:, 3:6, 3:6]

        # CBF 1: Inter-agent Collision Barrier (||delta_p|| >= 1.2m)
        rel_pos = self.follow_pos - self.lead_pos
        dist_sq = torch.sum(rel_pos**2, dim=-1, keepdim=True)
        h_collision = dist_sq - 1.44
        h_coll_dot = 2.0 * torch.sum(rel_pos * (self.follow_vel - self.lead_vel), dim=-1, keepdim=True)
        A_cbf1 = -2.0 * rel_pos.unsqueeze(1)
        b_cbf1 = (h_coll_dot * 2.0 + h_collision * 2.5).unsqueeze(-1)

        # CBF 2: Vortex Sinkhole Barrier (Stay in the exterior upwash zone, avoid downwash core)
        rel_pos_lead = torch.matmul(self.lead_rot.transpose(-1, -2), rel_pos.unsqueeze(-1)).squeeze(-1)
        h_sink = -(rel_pos_lead[:, 1:2] + (SPAN_EFF * 0.5 + 0.05))
        lead_y_axis = self.lead_rot[:, :, 1]
        A_cbf2 = lead_y_axis.unsqueeze(1)
        b_cbf2 = (4.0 * h_sink).unsqueeze(-1)

        # NCM Contraction Inequality: Ensures trajectory contraction rate alpha >= 1.2
        A_ncm = torch.matmul(P_sub, error_vel.unsqueeze(-1)).transpose(-1, -2)
        contraction_bound = 1.2 * torch.sum(error_vel * torch.matmul(P_sub, error_vel.unsqueeze(-1)).squeeze(-1), dim=-1, keepdim=True)
        b_ncm = (contraction_bound - 1.2 * torch.sum(error_pos * error_vel, dim=-1, keepdim=True)).unsqueeze(-1)

        A_constraints = torch.cat([A_cbf1, A_cbf2, A_ncm], dim=1)
        b_constraints = torch.cat([b_cbf1, b_cbf2, b_ncm], dim=1)

        certified_accel = self.qp_filter.solve(
            u_nom,
            A_constraints,
            b_constraints,
            u_min=torch.tensor([-6.0, -6.0, -3.5], device=self.device),
            u_max=torch.tensor([6.0, 6.0, 6.0], device=self.device),
        )

        # 6. Physical Actuator Synthesis with Energy-Harvesting Upwash Ingestion
        upwash_lift = 0.5 * AIR_DENSITY * 0.28 * wz_experienced * torch.abs(wz_experienced)

        Fz_req = (DRONE_MASS * (GRAVITY + certified_accel[:, 2:3]) - upwash_lift).clamp(
            min=2.0, max=30.0
        )
        tau_cmd = certified_accel[:, 0:2] * 0.12
        tau_yaw = torch.zeros((N, 1), device=self.device)

        cmd_wrench = torch.cat([Fz_req, tau_cmd, tau_yaw], dim=-1)
        raw_thrusts = torch.matmul(cmd_wrench, self.B_inv.T)
        target_thrusts = torch.clamp(raw_thrusts, 0.0, MAX_THRUST_PER_MOTOR)

        alpha_m = self.dt / (MOTOR_TAU + self.dt)
        self.follow_motors = self.follow_motors + alpha_m * (target_thrusts - self.follow_motors)
        self.follow_thrust = torch.sum(self.follow_motors, dim=-1, keepdim=True)

        accel_realized = torch.cat(
            [certified_accel[:, 0:2], (self.follow_thrust + upwash_lift) / DRONE_MASS - GRAVITY],
            dim=-1,
        )
        self.follow_vel = self.follow_vel + accel_realized * self.dt
        self.follow_pos = self.follow_pos + self.follow_vel * self.dt
        self.follow_rot = self.lead_rot.clone()

        baseline_hover_power = torch.sum(
            (torch.full_like(self.follow_motors, (DRONE_MASS * GRAVITY) / 4.0)) * 18.5 * MOTOR_COIL_RESISTANCE,
            dim=-1,
        )
        surfing_power = torch.sum(self.follow_motors * 18.5 * MOTOR_COIL_RESISTANCE, dim=-1)
        power_saved_pct = ((baseline_hover_power - surfing_power) / baseline_hover_power) * 100.0

        self.metrics = {
            "upwash_ms": wz_experienced.mean().item(),
            "thrust_relief_N": (DRONE_MASS * GRAVITY - self.follow_thrust.mean()).item(),
            "power_saved_pct": power_saved_pct.mean().item(),
            "h_sink": h_sink.mean().item(),
            "dist_lead": safe_norm(self.follow_pos - self.lead_pos, dim=-1).mean().item(),
        }
        return self.metrics



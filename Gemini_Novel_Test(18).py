class CertifiedWakeSurfingEnv:
    """
    Two-Quadrotor Aerodynamic Formation Environment with Lamb-Oseen wake coupling.
    Lead drone generates wake; follower identifies upwash zone and rides it
    under NCM contraction guarantees and CBF barrier enforcement.
    """

    def __init__(self, num_envs=1, dt=0.015, device=DEVICE):
        self.num_envs = num_envs
        self.dt = dt
        self.device = device

        self.wake_model = BurnhamHallockWakeField()
        self.qp_filter = BatchedQPSafetyFilter()

        # Quadrotor Actuator allocation
        d = ARM_LENGTH / math.sqrt(2.0)
        c_q = TORQUE_TO_THRUST_RATIO
        B = torch.tensor(
            [
                [1.0, 1.0, 1.0, 1.0],
                [d, -d, d, -d],
                [-d, d, d, -d],
                [-c_q, -c_q, c_q, c_q],
            ],
            device=device,
            dtype=torch.float32,
        )
        self.B_inv = torch.pinverse(B)
        self.inertia = torch.tensor(
            [0.021, 0.021, 0.036], device=device, dtype=torch.float32
        )
        self.inv_inertia = 1.0 / self.inertia

        self.reset()

    def reset(self):
        N = self.num_envs
        # Lead Drone: Cruising at (x=0, y=0, z=6.0)
        self.lead_pos = torch.zeros((N, 3), device=self.device)
        self.lead_pos[:, 2] = 6.0
        self.lead_vel = torch.zeros((N, 3), device=self.device)
        self.lead_vel[:, 0] = 3.5  # Cruising forward at 3.5 m/s

        # Follower Drone: Spawns trailing at x = -2.2m, y = -0.9m (Near upwash flank)
        self.follow_pos = torch.zeros((N, 3), device=self.device)
        self.follow_pos[:, 0] = -2.2
        self.follow_pos[:, 1] = -0.9
        self.follow_pos[:, 2] = 6.0
        self.follow_vel = self.lead_vel.clone()

        self.lead_rot = (
            torch.eye(3, device=self.device).unsqueeze(0).repeat(N, 1, 1)
        )
        self.follow_rot = self.lead_rot.clone()
        self.follow_omega = torch.zeros((N, 3), device=self.device)

        self.lead_thrust = torch.full(
            (N, 1), DRONE_MASS * GRAVITY, device=self.device
        )
        self.follow_thrust = self.lead_thrust.clone()
        self.follow_motors = torch.full(
            (N, 4), (DRONE_MASS * GRAVITY) / 4.0, device=self.device
        )

        self.estimated_upwash = torch.zeros((N, 1), device=self.device)
        self.metrics = {}

    def step(self, follower_nominal_accel, ncm_net):
        """
        Executes one synchronized aerodynamic timestep.
        1. Lead drone generates wake.
        2. Follower runs CBF-NCM QP to guarantee safety & stability in shear layer.
        3. Integrates SO(3) physics with non-stationary aerodynamics.
        """
        N = self.num_envs

        # 1. Lead drone dynamic cruise trajectory (smooth figure-8 or forward sweep)
        self.lead_pos = self.lead_pos + self.lead_vel * self.dt
        lead_drag = -0.5 * AIR_DENSITY * 0.22 * self.lead_vel * safe_norm(self.lead_vel, dim=-1, keepdim=True)
        self.lead_thrust = torch.full((N, 1), DRONE_MASS * GRAVITY, device=self.device) - lead_drag[:, 2:3]

        # 2. Sample wake vortex velocity field at follower rotor positions
        v_induced_follower = self.wake_model.compute_induced_velocity(
            self.follow_pos, self.lead_pos, self.lead_vel, self.lead_thrust
        )
        wz_experienced = v_induced_follower[:, 2:3]
        self.estimated_upwash = wz_experienced.detach()

        # 3. Macro-Planner Sweet Spot (Layer 1): The upwash maximum sits outside the core at y = -b/2 - 0.22m
        optimal_offset = torch.tensor([-2.0, -(SPAN_EFF * 0.5 + 0.24), 0.05], device=self.device)
        target_pos = self.lead_pos + optimal_offset
        target_vel = self.lead_vel

        # 4. Certified Micro-Reflex Layer (Layer 2: NCM + CBF QP)
        error_pos = self.follow_pos - target_pos
        error_vel = self.follow_vel - target_vel
        state_error = torch.cat([error_pos, error_vel], dim=-1)

        # Evaluate Learned Metric M(x)
        M = ncm_net(state_error)
        P_sub = M[:, 3:6, 3:6]  # Velocity block

        # CBF 1: Inter-agent Collision Barrier (||delta_p||^2 >= 1.2^2)
        rel_pos = self.follow_pos - self.lead_pos
        dist_sq = torch.sum(rel_pos**2, dim=-1, keepdim=True)
        h_collision = dist_sq - 1.44
        h_coll_dot = 2.0 * torch.sum(rel_pos * (self.follow_vel - self.lead_vel), dim=-1, keepdim=True)
        A_cbf1 = -2.0 * rel_pos.unsqueeze(1)
        b_cbf1 = (h_coll_dot * 2.5 + h_collision * 3.0).unsqueeze(-1)

        # CBF 2: Vortex Sinkhole Barrier (Stay clear of lead downwash center line)
        # Prevents follower from crossing inside y_rel >= -b/2 + 0.05
        y_rel = self.follow_pos[:, 1:2] - self.lead_pos[:, 1:2]
        h_sink = -(y_rel + (SPAN_EFF * 0.5 - 0.06))  # Must remain negative (lateral exterior)
        A_cbf2 = torch.zeros((N, 1, 3), device=self.device)
        A_cbf2[:, 0, 1] = 1.0
        b_cbf2 = (-5.0 * (self.follow_vel[:, 1:2] - self.lead_vel[:, 1:2]) + 4.0 * h_sink).unsqueeze(-1)

        # NCM Contraction Inequality: Forces exponential trajectory contraction
        # (v_error)^T P_sub u <= b_ncm
        A_ncm = (torch.matmul(P_sub, error_vel.unsqueeze(-1)).transpose(-1, -2))
        contraction_decay = 2.2 * torch.sum(error_vel * torch.matmul(P_sub, error_vel.unsqueeze(-1)).squeeze(-1), dim=-1, keepdim=True)
        b_ncm = (contraction_decay - 1.5 * torch.sum(error_pos * error_vel, dim=-1, keepdim=True)).unsqueeze(-1)

        A_constraints = torch.cat([A_cbf1, A_cbf2, A_ncm], dim=1)
        b_constraints = torch.cat([b_cbf1, b_cbf2, b_ncm], dim=1)

        # Solve Real-Time QP Safety Filter
        certified_accel = self.qp_filter.solve(
            follower_nominal_accel,
            A_constraints,
            b_constraints,
            u_min=torch.tensor([-8.0, -8.0, -4.0], device=self.device),
            u_max=torch.tensor([8.0, 8.0, 12.0], device=self.device),
        )

        # 5. Actuator Wrench Synthesis with Harvested Upwash Ingestion
        apparent_vel = self.follow_vel - v_induced_follower
        induced_updraft_force = 0.5 * AIR_DENSITY * 0.28 * wz_experienced * torch.abs(wz_experienced)

        # Net vehicle vertical thrust required to maintain altitude
        Fz_req = (DRONE_MASS * (GRAVITY + certified_accel[:, 2:3]) - induced_updraft_force).clamp(
            min=2.0, max=32.0
        )
        tau_cmd = certified_accel[:, 0:2] * 0.12
        tau_yaw = torch.zeros((N, 1), device=self.device)

        cmd_wrench = torch.cat([Fz_req, tau_cmd, tau_yaw], dim=-1)
        raw_thrusts = torch.matmul(cmd_wrench, self.B_inv.T)
        target_thrusts = torch.clamp(raw_thrusts, 0.0, MAX_THRUST_PER_MOTOR)

        # Actuator lag
        alpha_m = self.dt / (MOTOR_TAU + self.dt)
        self.follow_motors = self.follow_motors + alpha_m * (target_thrusts - self.follow_motors)
        self.follow_thrust = torch.sum(self.follow_motors, dim=-1, keepdim=True)

        # 6. Translational & Rotational Kinematics
        accel_realized = (
            torch.cat([certified_accel[:, 0:2], (self.follow_thrust + induced_updraft_force) / DRONE_MASS - GRAVITY], dim=-1)
        )
        self.follow_vel = self.follow_vel + accel_realized * self.dt
        self.follow_pos = self.follow_pos + self.follow_vel * self.dt

        # Power dissipation metric
        baseline_hover_power = torch.sum((torch.full_like(self.follow_motors, (DRONE_MASS * GRAVITY) / 4.0)) * 18.5 * MOTOR_COIL_RESISTANCE, dim=-1)
        surfing_power = torch.sum(self.follow_motors * 18.5 * MOTOR_COIL_RESISTANCE, dim=-1)
        power_saved_pct = ((baseline_hover_power - surfing_power) / baseline_hover_power) * 100.0

        self.metrics = {
            "upwash_ms": wz_experienced.mean().item(),
            "thrust_reduction_N": (DRONE_MASS * GRAVITY - self.follow_thrust.mean()).item(),
            "power_saved_pct": power_saved_pct.mean().item(),
            "dist_to_leader": safe_norm(self.follow_pos - self.lead_pos, dim=-1).mean().item(),
            "h_sink": h_sink.mean().item(),
        }
        return self.metrics



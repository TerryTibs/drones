# 3. REAL-TIME BATCHED QP SAFETY & CONTRACTION FILTER
# =============================================================================
class BatchedQPSafetyFilter:
    """
    Solves a real-time Second-Order / Quadratic Program across 12k environments:
        min_u 0.5 * ||u - u_nominal||^2
        s.t.  A_cbf * u <= b_cbf  (Collision Barrier & Vortex Sinkhole Barrier)
              A_ncm * u <= b_ncm  (Exponential Riemannian Contraction Bound)
    Implemented via vectorized Projected Primal-Dual Active-Set on CUDA.
    """

    def __init__(self, max_iters=25, tol=1e-4):
        self.max_iters = max_iters
        self.tol = tol

    def solve(self, u_nom, A, b, u_min, u_max):
        """
        u_nom: [N, m] nominal acceleration command
        A: [N, k, m] inequality constraint matrix
        b: [N, k, 1] constraint bounds (A u <= b)
        """
        N, m = u_nom.shape
        k = A.shape[1]

        u = torch.clamp(u_nom, u_min, u_max).clone()
        lam = torch.zeros((N, k, 1), device=u.device, dtype=torch.float32)
        rho = 1.2

        At = A.transpose(-1, -2)
        H_inv = torch.inverse(
            torch.eye(m, device=u.device).unsqueeze(0).repeat(N, 1, 1)
            + rho * torch.matmul(At, A)
        )

        for _ in range(self.max_iters):
            # Primal step
            v = b - torch.matmul(A, u.unsqueeze(-1)) - (lam / rho)
            slack = F.relu(-v)
            rhs = u_nom.unsqueeze(-1) + torch.matmul(
                At, rho * (b - slack) - lam
            )
            u_next = torch.matmul(H_inv, rhs).squeeze(-1)
            u = torch.clamp(u_next, u_min, u_max)

            # Dual step
            viol = torch.matmul(A, u.unsqueeze(-1)) - b
            lam = F.relu(lam + rho * (viol + slack))

        return u



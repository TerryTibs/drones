# 1. DIFFERENTIABLE LAMB-OSEEN TIP-VORTEX WAKE FILAMENT MODEL
# =============================================================================
class BurnhamHallockWakeField:
    """
    Computes 3D induced velocity field generated by the lead drone's trailing
    counter-rotating tip vortices. Features an induced downwash core between
    rotors and an energetic upwash harvesting flank outside the vortex lines.
    """

    def __init__(self, span=SPAN_EFF, r_core=VORTEX_CORE_RADIUS, rho=AIR_DENSITY):
        self.b = span
        self.r_c = r_core
        self.rho = rho

    def compute_induced_velocity(self, eval_pos, leader_pos, leader_vel, leader_thrust):
        """
        eval_pos: [N, 3] points where air velocity is sampled
        leader_pos: [N, 3] position of wake generator
        leader_vel: [N, 3] velocity of wake generator
        leader_thrust: [N, 1] total vertical thrust generated
        """
        N = eval_pos.shape[0]
        fwd_speed = safe_norm(leader_vel[:, 0:2], dim=-1, keepdim=True).clamp(min=1.5)

        # Circulation magnitude Gamma_0 = Thrust / (rho * v_forward * b)
        gamma_0 = leader_thrust / (self.rho * fwd_speed * self.b).clamp(min=1e-3)
        gamma_0 = torch.clamp(gamma_0, min=0.5, max=18.0)

        # Displacement from leader in lead-drone relative coordinates
        delta = eval_pos - leader_pos
        dx = delta[:, 0:1]
        dy = delta[:, 1:2]
        dz = delta[:, 2:3]

        # Vortex cores are shed at y = ± b/2 and trail downstream behind the leader (dx < 0)
        wake_decay = torch.exp(torch.clamp(dx / 8.0, max=0.0))  # Decays ahead of drone

        # Left vortex (CCW, positioned at y = -b/2)
        r_left_sq = (dy + self.b * 0.5) ** 2 + dz**2
        v_theta_left = (gamma_0 / (2.0 * math.pi)) * (
            r_left_sq / (r_left_sq + self.r_c**2)
        ) / torch.sqrt(r_left_sq.clamp(min=1e-4))

        # Right vortex (CW, positioned at y = +b/2)
        r_right_sq = (dy - self.b * 0.5) ** 2 + dz**2
        v_theta_right = -(gamma_0 / (2.0 * math.pi)) * (
            r_right_sq / (r_right_sq + self.r_c**2)
        ) / torch.sqrt(r_right_sq.clamp(min=1e-4))

        # Velocity decomposition in Cartesian coordinates
        wz_left = v_theta_left * ((dy + self.b * 0.5) / torch.sqrt(r_left_sq.clamp(min=1e-4)))
        wy_left = -v_theta_left * (dz / torch.sqrt(r_left_sq.clamp(min=1e-4)))

        wz_right = v_theta_right * ((dy - self.b * 0.5) / torch.sqrt(r_right_sq.clamp(min=1e-4)))
        wy_right = -v_theta_right * (dz / torch.sqrt(r_right_sq.clamp(min=1e-4)))

        # Total induced wind vector [wx, wy, wz]
        w_y = (wy_left + wy_right) * wake_decay
        w_z = (wz_left + wz_right) * wake_decay
        w_x = -0.15 * torch.abs(w_z)  # Induced downwash back-drag

        v_induced = torch.cat([w_x, w_y, w_z], dim=-1)
        return torch.where(dx > 0.1, torch.zeros_like(v_induced), v_induced)


def safe_norm(x, dim=-1, keepdim=False, eps=1e-12):
    return torch.sqrt(torch.sum(x * x, dim=dim, keepdim=keepdim) + eps)



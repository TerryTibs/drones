# 2. NEURAL CONTRACTION METRIC (NCM) & RIEMANNIAN METRIC TENSOR
# =============================================================================
class NeuralContractionMetric(nn.Module):
    """
    Deep Riemannian Metric Tensor M(x) = L(x) L(x)^T + eps * I.
    Guarantees that all neighboring trajectories contract exponentially:
    d/dt [delta_x^T M(x) delta_x] <= -2 * alpha * [delta_x^T M(x) delta_x]
    """

    def __init__(self, state_dim=6, alpha=2.2):
        super().__init__()
        self.state_dim = state_dim
        self.alpha = alpha
        self.net = nn.Sequential(
            nn.Linear(state_dim, 64),
            nn.SiLU(),
            nn.Linear(64, 64),
            nn.SiLU(),
            nn.Linear(64, (state_dim * (state_dim + 1)) // 2),
        )
        self.tril_indices = torch.tril_indices(state_dim, state_dim)

    def forward(self, state_error):
        """
        state_error: [N, 6] representing [p - p*, v - v*]
        Returns M: [N, 6, 6] symmetric positive definite Riemannian metric
        """
        N = state_error.shape[0]
        params = self.net(state_error)
        L = torch.zeros(
            (N, self.state_dim, self.state_dim),
            device=state_error.device,
            dtype=torch.float32,
        )
        L[:, self.tril_indices[0], self.tril_indices[1]] = params

        # Ensure strict positive-definiteness on diagonal
        diag_idx = torch.arange(self.state_dim)
        L[:, diag_idx, diag_idx] = F.softplus(L[:, diag_idx, diag_idx]) + 0.15

        # M = L * L^T + eps * I
        M = torch.matmul(L, L.transpose(-1, -2)) + 0.08 * torch.eye(
            self.state_dim, device=state_error.device
        ).unsqueeze(0)
        return M


